use crate::ast::*;
use std::fs;
use std::path::PathBuf;

#[derive(Debug, Clone)]
pub struct GenConfig {
    pub languages: Vec<TargetLang>,
    pub out_dir: PathBuf,
    pub generate_messages: bool,
    pub generate_grpc: bool,
    pub dry_run: bool,
}

#[derive(Debug, Clone)]
pub struct GeneratedArtifact {
    pub lang: TargetLang,
    #[allow(dead_code)]
    pub proto_source: String,
    pub output_path: PathBuf,
    #[allow(dead_code)]
    pub content: String,
    pub bytes: usize,
}

pub fn split_words(s: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for i in 0..chars.len() {
        let c = chars[i];
        if c == '_' || c == '-' || c == '.' || c == ' ' || c == '/' {
            if !cur.is_empty() {
                words.push(std::mem::take(&mut cur));
            }
            continue;
        }
        if c.is_ascii_uppercase() && !cur.is_empty() {
            let prev = chars[i - 1];
            let next_is_lower = chars.get(i + 1).map_or(false, |n| n.is_ascii_lowercase());
            if prev.is_ascii_lowercase()
                || prev.is_ascii_digit()
                || (prev.is_ascii_uppercase() && next_is_lower)
            {
                words.push(std::mem::take(&mut cur));
            }
        }
        cur.push(c.to_ascii_lowercase());
    }
    if !cur.is_empty() {
        words.push(cur);
    }
    words
}

pub fn to_pascal_case(s: &str) -> String {
    split_words(s)
        .into_iter()
        .map(|w| {
            let mut ch = w.chars();
            match ch.next() {
                None => String::new(),
                Some(first) => first.to_ascii_uppercase().to_string() + ch.as_str(),
            }
        })
        .collect()
}

pub fn to_camel_case(s: &str) -> String {
    let pas = to_pascal_case(s);
    let mut ch = pas.chars();
    match ch.next() {
        None => String::new(),
        Some(first) => first.to_ascii_lowercase().to_string() + ch.as_str(),
    }
}

pub fn to_snake_case(s: &str) -> String {
    split_words(s).join("_")
}

pub fn to_screaming_snake_case(s: &str) -> String {
    to_snake_case(s).to_ascii_uppercase()
}

pub fn banner_comment(file: &ProtoFile, lang: TargetLang, prefix: &str) -> String {
    format!(
        "{p} @generated by ProtoBuilder v1.0.0 — DO NOT EDIT.\n\
         {p} Source: {src} (syntax: {syn}, package: {pkg})\n\
         {p} Target: {target}\n\n",
        p = prefix,
        src = file.name,
        syn = file.syntax.as_str(),
        pkg = if file.package.is_empty() {
            "<default>"
        } else {
            &file.package
        },
        target = lang.display_name(),
    )
}

pub fn generate_for_file(
    file: &ProtoFile,
    lang: TargetLang,
    cfg: &GenConfig,
) -> Vec<(String, String)> {
    match lang {
        TargetLang::Rust => langs_a::gen_rust(file, cfg),
        TargetLang::Go => langs_a::gen_go(file, cfg),
        TargetLang::Python => langs_a::gen_python(file, cfg),
        TargetLang::TypeScript => langs_a::gen_typescript(file, cfg),
        TargetLang::JavaScript => langs_a::gen_javascript(file, cfg),
        TargetLang::Cpp => langs_b::gen_cpp(file, cfg),
        TargetLang::Java => langs_b::gen_java(file, cfg),
        TargetLang::Kotlin => langs_b::gen_kotlin(file, cfg),
        TargetLang::CSharp => langs_b::gen_csharp(file, cfg),
        TargetLang::Swift => langs_b::gen_swift(file, cfg),
        TargetLang::Dart => langs_c::gen_dart(file, cfg),
        TargetLang::Php => langs_c::gen_php(file, cfg),
        TargetLang::Ruby => langs_c::gen_ruby(file, cfg),
        TargetLang::ObjC => langs_c::gen_objc(file, cfg),
        TargetLang::C => langs_c::gen_c(file, cfg),
    }
}

pub fn run_codegen(bundle: &SchemaBundle, cfg: &GenConfig) -> Result<Vec<GeneratedArtifact>, String> {
    let mut artifacts = Vec::new();
    let multi_lang = cfg.languages.len() > 1;

    for file in &bundle.files {
        if file.is_wkt {
            continue;
        }
        for &lang in &cfg.languages {
            let base_dir = if multi_lang {
                cfg.out_dir.join(lang.canonical_id())
            } else {
                cfg.out_dir.clone()
            };

            let files = generate_for_file(file, lang, cfg);
            for (rel_name, content) in files {
                let out_path = base_dir.join(&rel_name);
                let bytes = content.len();
                if !cfg.dry_run {
                    if let Some(parent) = out_path.parent() {
                        fs::create_dir_all(parent).map_err(|e| {
                            format!(
                                "Failed to create output directory '{}': {}",
                                parent.display(),
                                e
                            )
                        })?;
                    }
                    fs::write(&out_path, &content).map_err(|e| {
                        format!(
                            "Failed to write generated file '{}': {}",
                            out_path.display(),
                            e
                        )
                    })?;
                }
                artifacts.push(GeneratedArtifact {
                    lang,
                    proto_source: file.name.clone(),
                    output_path: out_path,
                    content,
                    bytes,
                });
            }
        }
    }

    Ok(artifacts)
}
